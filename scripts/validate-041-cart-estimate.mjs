import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const file = new URL('../wp-content/plugins/petshop-core/assets/src/shared/cart-estimate.js', import.meta.url);
const response = fs.existsSync(file) ? null : await fetch(`${process.env.PETSHOP_BASE_URL || 'http://wordpress'}/wp-content/plugins/petshop-core/assets/src/shared/cart-estimate.js`);
if (response) assert(response.ok, 'Estimate asset must be delivered');
const context = vm.createContext({ window: {} });
vm.runInContext(response ? await response.text() : fs.readFileSync(file, 'utf8'), context);
const { amount, total } = context.window.petshopCartEstimate;
const item = { prices: { price: '2800', currency_code: 'BRL', currency_minor_unit: 2 }, totals: { line_total: '2400' } };
const before = JSON.stringify(item);
assert.equal(amount(item, 5), 14000);
assert.equal(amount({ prices: { ...item.prices, price: '29' } }, 3), 87);
assert.equal(amount({ prices: { ...item.prices, price: '0' } }, 5), 0);
for (const quantity of [0, -1, 1.5, NaN, Infinity]) assert.equal(amount(item, quantity), null);
for (const price of ['1.20', '-100', 'invalid', '99999999999999999']) assert.equal(amount({ prices: { ...item.prices, price } }, 5), null);
assert.equal(amount({ prices: { ...item.prices, price: '9007199254740991' } }, 2), null);
assert.equal(total([{ item, quantity: 5 }, { item, quantity: 2 }]), 19600);
assert.equal(total([{ item, quantity: 5 }, { item: { prices: { ...item.prices, currency_code: 'USD' } }, quantity: 2 }]), null);
assert.equal(total([{ item, quantity: 5 }, { item: { prices: { ...item.prices, currency_minor_unit: 0 } }, quantity: 2 }]), null);
assert.equal(total([]), null);
assert.equal(JSON.stringify(item), before, 'Estimates must not mutate official prices/discounts/cart totals');
console.log('041 cart estimate: integer currency, invalid/overflow/mixed currencies, zero and official data preservation passed');
